create table tennis.standings (
    id bigint generated by default as identity primary key,
    event_id uuid not null references tennis.events(id) on update cascade on delete cascade,
    group_name text not null,
    entry_id uuid not null references tennis.entries(id) on update cascade on delete cascade,
    position int not null, -- not unique per group since there might be a tie
    ties_won int,
    ties_lost int,
    matches_won int not null,
    matches_lost int not null,
    sets_won int not null,
    sets_lost int not null,
    games_won int not null,
    games_lost int not null,
    round_id uuid not null references tennis.rounds(id) on update cascade on delete cascade
);

grant select on table tennis.standings to anon;
grant all privileges on table tennis.standings to authenticated;

alter table tennis.standings enable row level security;
create policy "Anyone can select" on tennis.standings for select to anon, authenticated using(true);
create policy "Authenticated can insert" on tennis.standings for insert to authenticated with check (true);
create policy "Authenticated can update" on tennis.standings for update to authenticated using (true) with check (true);
create policy "Authenticated can delete" on tennis.standings for delete to authenticated using (true);
